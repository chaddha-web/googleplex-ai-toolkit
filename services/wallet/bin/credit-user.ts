/**
 * Admin credit tool — credit a real account's wallet (off-camera funding).
 *
 * Looks up the account by email, credits the ledger for the given asset/amount,
 * records a deposit + ledger entry (so it shows in transaction history), drives
 * wallet activation (when total stablecoin balance ≥ the $1 floor), and emails
 * the branded deposit confirmation.
 *
 * Usage (inside the wallet container on the box):
 *   docker exec -it gplex-wallet \
 *     npx tsx --env-file=.env bin/credit-user.ts \
 *       --email someone@example.com --amount 1 --asset USDT --chain bsc
 *
 * Notes:
 *   • The account must have opened its wallet once (auto-provisions addresses).
 *   • This credits the LEDGER (what the app shows); it does not move real funds.
 *   • Seva Credit (10B) is still generated by the member via the dashboard.
 */
import { db } from "../src/db/index.js";
import { ledgerBalances, ledgerEntries, deposits, userWalletAddresses } from "../src/db/schema.js";
import { findToken } from "../src/tokens.js";
import { eq, and } from "drizzle-orm";
import { ulid } from "ulid";

function arg(name: string, def?: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : def;
}

const AUTH_BASE = (process.env.AUTH_BASE_URL || "http://localhost:4200").replace(/\/$/, "");
const INTERNAL = process.env.INTERNAL_SERVICE_TOKEN;

function toRawUnits(amount: number, decimals: number): bigint {
  const p = Math.min(decimals, 6);
  const head = BigInt(Math.round(amount * 10 ** p));
  return head * 10n ** BigInt(Math.max(0, decimals - p));
}
function fakeTxHash(chain: string): string {
  const hex = Array.from({ length: 64 }, () => "0123456789abcdef"[Math.floor(Math.random() * 16)]).join("");
  return chain === "eth" || chain === "bsc" ? "0x" + hex : hex;
}
function sender(chain: string): string {
  switch (chain) {
    case "tron": return "TWd4xK9mFundingTreasury8sQp4rVnLzAbc";
    case "btc": return "bc1qfundingtreasury0xref9p3k2m8s7q4t6";
    default: return "0xFund1ngTreasury00000000000000000A1b2C3d";
  }
}

async function main() {
  const email = arg("email");
  const asset = arg("asset", "USDT")!;
  const chain = arg("chain", "bsc")!;
  const amount = Number(arg("amount", "1"));
  if (!email || !amount || amount <= 0) {
    console.error("Usage: --email <e> --amount <n> [--asset USDT] [--chain bsc|tron|eth]");
    process.exit(1);
  }
  if (!INTERNAL) { console.error("INTERNAL_SERVICE_TOKEN not set"); process.exit(1); }

  // 1) Resolve the account.
  const look = await fetch(`${AUTH_BASE}/internal/users/lookup?email=${encodeURIComponent(email)}`, {
    headers: { Authorization: "Bearer " + INTERNAL }
  });
  if (!look.ok) { console.error(`lookup failed (${look.status}) — does the account exist?`); process.exit(1); }
  const u = (await look.json()) as any;
  const userId = u.id as string;

  // 2) Must be provisioned (user opened their wallet once).
  const prov = db.select().from(userWalletAddresses).where(eq(userWalletAddresses.user_id, userId)).limit(1).all();
  if (prov.length === 0) { console.error("Wallet not provisioned yet — open the Wallet page once, then re-run."); process.exit(1); }

  const token = findToken(chain as any, asset);
  if (!token) { console.error(`Unsupported ${asset} on ${chain}`); process.exit(1); }
  const amountRaw = toRawUnits(amount, token.decimals);
  const txHash = fakeTxHash(chain);
  const now = Date.now();
  const dId = ulid();

  // 3) Credit ledger + record deposit + entry.
  db.transaction((tx) => {
    const rows = tx.select().from(ledgerBalances)
      .where(and(eq(ledgerBalances.user_id, userId), eq(ledgerBalances.chain, chain), eq(ledgerBalances.symbol, asset)))
      .limit(1).all();
    if (rows.length === 0) {
      tx.insert(ledgerBalances).values({ user_id: userId, chain, symbol: asset, raw: amountRaw.toString(), decimals: token.decimals, updated_at: now }).run();
    } else {
      tx.update(ledgerBalances).set({ raw: (BigInt(rows[0]!.raw) + amountRaw).toString(), updated_at: now })
        .where(and(eq(ledgerBalances.user_id, userId), eq(ledgerBalances.chain, chain), eq(ledgerBalances.symbol, asset))).run();
    }
    tx.insert(deposits).values({ id: dId, user_id: userId, chain, symbol: asset, amount_raw: amountRaw.toString(), tx_hash: txHash, from_address: sender(chain), block_number: null, confirmed_at: now, credited_at: now }).run();
    tx.insert(ledgerEntries).values({ id: ulid(), user_id: userId, chain, symbol: asset, delta_raw: amountRaw.toString(), kind: "deposit", ref_tx_hash: txHash, ref_id: dId, created_at: now }).run();
  });

  // 4) Activation — cumulative stablecoin USD at face value (USDT/USDC = $1).
  const all = db.select().from(ledgerBalances).where(eq(ledgerBalances.user_id, userId)).all();
  let totalUsd = 0;
  for (const b of all) {
    if (["USDT", "USDC"].includes(b.symbol) && ["eth", "bsc", "tron"].includes(b.chain)) {
      totalUsd += Number(BigInt(b.raw)) / 10 ** b.decimals;
    }
  }
  await fetch(`${AUTH_BASE}/internal/users/${userId}/wallet-status`, {
    method: "POST",
    headers: { "Content-Type": "application/json", Authorization: "Bearer " + INTERNAL },
    body: JSON.stringify({ initialDepositCreditedUsd: totalUsd })
  });

  // 5) Branded deposit email (best-effort).
  await fetch(`${AUTH_BASE}/internal/email/deposit`, {
    method: "POST",
    headers: { "Content-Type": "application/json", Authorization: "Bearer " + INTERNAL },
    body: JSON.stringify({ userId, amount: String(amount), symbol: asset, chain, usd: amount, txHash })
  }).catch(() => {});

  console.log(`✅ Credited ${amount} ${asset} (${chain}) to ${email}`);
  console.log(`   tx: ${txHash}`);
  console.log(`   total stablecoin balance now ≈ $${totalUsd.toFixed(2)}  ${totalUsd >= 1 ? "(wallet ACTIVE)" : ""}`);
  process.exit(0);
}
main().catch((e) => { console.error("credit failed:", e); process.exit(1); });
